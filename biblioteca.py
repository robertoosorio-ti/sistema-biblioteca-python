#Biblioteca

# importamos datetime para poder colocar la hora de ingreso a cada estudiante
import datetime

#esta variable guardara la entrada de cada estudiante con su hora

registro_accesos = []


# Lista de estudiantes registrados
# Cada estudiante tendra una lista [rut, nombre, carrera]

estudiantes = []

# Esta lista tendra los estudiantes dentro de la biblioteca

en_biblioteca = []


#esta funcion sirve para agregar estudiantes

def ingresar_estudiante():

  rut_ingreso = input("Ingrese su rut: ").strip()
  if rut_ingreso == "":
        print("El rut no puede estar vacío.")
        return  # corta la funcion no sigue registrando

  encontrado = False

  for estudiante in estudiantes:

#aqui el sistema reconoce estudiantes ya registrados anteriormente

    if estudiante[0] == rut_ingreso:

      print("Bienvenido, ya estas registrado en el sistema")

      encontrado = True


#en caso de no estar registrado pide los siguientes datos

  if encontrado == False:

      nombre_ingreso = input("Ingrese nombre: ").lower().strip()

      carrera_ingreso = input("Ingrese carrera: ").lower().strip()
      #ponemos .lower() para que sea en minuscula y no tengamos dos carreras #del #mismo nombre porque el usuario escribio distinto ejemplo #INFORMATICA o informatica lo mismo con .strip que es para eliminar #espacios antes y al #final

      nuevo_estudiante = [rut_ingreso, nombre_ingreso, carrera_ingreso]

      estudiantes.append(nuevo_estudiante)

      print("Estudiante registrado exitosamente.")

#aqui se guarda la hora actual que despues se mostrara en el listado
  hora_actual = datetime.datetime.now()
  registro_accesos.append([rut_ingreso, hora_actual])



#si se ingresa el rut y el estudiante se encuentra en biblioteca el sistema
#avisa

  if rut_ingreso in en_biblioteca:

    print("El estudiante se encuentra en biblioteca")

  else:

    en_biblioteca.append(rut_ingreso)
#funcion que sirve para sacar al estudiante de biblioteca

def salir_estudiante():
  rut_salida = input("Ingrese rut para salir: ").strip()
  if rut_salida in en_biblioteca:
    en_biblioteca.remove(rut_salida)
    print("¡Salida registrada con exito!")
  else:
    print("El rut no esta registrado en biblioteca.")

#esta lista de estudiantes incluye una sub-lista para poder buscar a un
#estudiante en especifico por el rut
def listar_estudiante():
  print("1. lista de estudiantes.\n2. Buscar estudiante por rut\n3. Ver accesos del dia\n4. Ver cantidad de estudiantes por carrera")
  respuesta = input("Elija una opcion: ")
  if respuesta == "1":
    for rut_ingreso in en_biblioteca:
      for estudiante in estudiantes:
        if estudiante[0] == rut_ingreso:
          hora = ""
          for registro in registro_accesos:
              if registro[0] == rut_ingreso:
                hora = registro[1]

          print(estudiante[0] + "|" + estudiante[1] + "|" + estudiante[2] + "|" + str(hora)[0:16])#se pone [0:16] para que solo arroje 16 caracteres #en la hora/fecha dejando asi hora y minutos

  elif respuesta == "2":
    rut_dentro = input("ingrese el rut: ")
    if rut_dentro in en_biblioteca:
      print("El estudiante esta registrado en biblioteca.")
      for estudiante in estudiantes:
        if estudiante[0] == rut_dentro:
          hora = ""
          for registro in registro_accesos:
              if registro[0] == rut_dentro:
                hora = registro[1]
          print(estudiante[0] + "|" + estudiante[1] + "|" + estudiante[2] + "|" + str(hora)[0:16])#se pone[0:16] para que solo arroje 16 caracteres #en la hora/fecha
    else:
      print("El estudiante no esta en biblioteca")
  elif respuesta == "3":
    print("Lista de accesos del dia.")

    for registro in registro_accesos:
      for estudiante in estudiantes:
        if registro[0] == estudiante[0]:

          print(estudiante[0] + "|" + estudiante[1] + "|" + estudiante[2] + "|" + str(registro[1])[0:16])

#aqui creamos un diccionario para buscar cuantas carreras hay inscritas ejem: #informatica:2
#medicina:1
  elif respuesta == "4":
    conteo_carrera = {}
    for estudiante in estudiantes:
      if estudiante[2] in conteo_carrera:
        conteo_carrera[estudiante[2]] += 1
      else:
        conteo_carrera[estudiante[2]] = 1
    for carrera in conteo_carrera:
      print(carrera + ":" + str(conteo_carrera[carrera]))


# Con while creamos el menu de opciones en un bucle  para poder crear eliminar # a estudiante de la biblioteca y consultar
# estudiantes
while True:

  print("1.ingresar\n2.salir\n3.listar\n4.terminar")

  opciones = input("Elija una opcion: ")

  if opciones == "1":
#ingresa opcion 1 sirve para poder "ingresar" estudiantes nuevos

   ingresar_estudiante()

  elif opciones == "2":
#ingresa opcion 2 sirve para poder quitar estudiantes de biblioteca

   salir_estudiante()


  elif opciones == "3":
#ingresa opcion 3 verificar lista de estudiantes dentro de biblioteca, busca estudiantes por rut, ver registro de ingresos diarios y ver la cantidad de estudiantes por carrera

   listar_estudiante()

  elif opciones == "4":
#ingresa opcion 4 termina el programa
    print("El Programa finalizo.")
    break
  else:
#opcion nula en caso del usuario ingresar palabras o numeros no existentes
#en el menu
    print("Opcion invalida, vuelva a intentar")